/**
 * Custom ribbon text for highlighted events: the text inputs in the event
 * form and the custom text on the event card ribbon. When it is off, saving
 * the form keeps a stored text and the card shows the default ribbon text.
 */
export function useRibbonText() {
  // Ribbon text: the feature's only switch, for every place it shows
  const ribbonText = true
  return ribbonText
}
